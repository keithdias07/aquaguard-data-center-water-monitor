#!/usr/bin/env node
/*
 * Writes data/extension/extension_stats_sample.json: a SYNTHETIC statistics
 * export so the dashboard has something to show before you export your own.
 * It is produced with the same reducer the extension uses, so its shape always
 * matches a real export. The numbers are made up (seeded random), not usage.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const S = require('../src/shared/settings.js');

let seed = 20261017;
function rand() {
  // mulberry32: small deterministic PRNG so the sample is reproducible
  seed |= 0;
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const pick = (arr) => arr[Math.floor(rand() * arr.length)];

const RULES = ['greeting', 'pleasantry', 'request-preamble', 'want-preamble', 'please-prefix', 'verbose-phrase', 'duplicate-sentence', 'whitespace'];
let stats = S.emptyStats();
const start = new Date(2026, 8, 1, 12);

for (let day = 0; day < 30; day++) {
  const date = new Date(start.getTime() + day * 86400000);
  const prompts = 3 + Math.floor(rand() * 12);
  for (let p = 0; p < prompts; p++) {
    const runs = 1 + Math.floor(rand() * 3);
    const hasSuggestion = rand() < 0.6;
    for (let r = 0; r < runs; r++) {
      stats = S.recordEvent(stats, { type: 'run', changed: hasSuggestion, latencyMs: 0.2 + rand() * 1.5 }, date);
    }
    let outcome = 'unchanged';
    if (hasSuggestion) {
      if (rand() < 0.7) {
        const original = 25 + Math.floor(rand() * 180);
        const optimized = Math.round(original * (0.7 + rand() * 0.25));
        const ruleIds = [...new Set([pick(RULES), pick(RULES)])];
        stats = S.recordEvent(stats, { type: 'applied', originalTokens: original, optimizedTokens: optimized, ruleIds }, date);
        outcome = 'optimized';
        if (rand() < 0.08) {
          stats = S.recordEvent(stats, { type: 'undone', tokensSaved: original - optimized }, date);
          outcome = 'declined';
        }
      } else {
        outcome = 'declined';
      }
    }
    stats = S.recordEvent(stats, { type: 'completed', outcome }, date);
  }
}

const out = S.exportStats(stats, { extensionVersion: '0.1.0', now: new Date('2026-10-01T00:00:00Z') });
out.sampleData = true;
out.note = 'SYNTHETIC SAMPLE generated by extension/eval/generate_sample_stats.js. Not real usage.';
const dest = path.join(__dirname, '..', '..', 'data', 'extension', 'extension_stats_sample.json');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${dest}`);
